    private void btnGenerarMatrizActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarMatrizActionPerformed
        // TODO add your handling code here: try {
        try {

    int cantidad = Integer.parseInt(txtCantidad.getText());

    if (cantidad <= 0) {
        JOptionPane.showMessageDialog(this,
                "La cantidad de nodos debe ser mayor que 0.");
        return;
    }

    String[] columnas = new String[cantidad];

    for (int i = 0; i < cantidad; i++) {
        columnas[i] = String.valueOf((char) ('A' + i));
    }

    Object[][] datos = new Object[cantidad][cantidad];

    for (int i = 0; i < cantidad; i++) {
        for (int j = 0; j < cantidad; j++) {
            datos[i][j] = 0;
        }
    }

    DefaultTableModel modelo =
            new DefaultTableModel(datos, columnas);

    tablaMatriz.setModel(modelo);

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Ingrese una cantidad válida de nodos.");
}

    
    }//GEN-LAST:event_btnGenerarMatrizActionPerformed

