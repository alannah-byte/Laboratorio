    private void btnGenerarGrafoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarGrafoActionPerformed
        // TODO add your handling code here:
        try {
            if (tablaMatriz.isEditing()) {
                tablaMatriz.getCellEditor().stopCellEditing();
            }

            int cantidad = tablaMatriz.getRowCount();
            int[][] matriz = new int[cantidad][cantidad];

            for (int i = 0; i < cantidad; i++) {
                for (int j = 0; j < cantidad; j++) {

                    int valor = Integer.parseInt(
                        tablaMatriz.getValueAt(i, j).toString()
                    );

                    if (valor != 0 && valor != 1) {
                        throw new IllegalArgumentException(
                            "Solo se permiten 0 y 1."
                        );
                    }

                    matriz[i][j] = valor;
                }
            }

            // Trabajaremos con grafos no dirigidos.
            for (int i = 0; i < cantidad; i++) {
                for (int j = 0; j < cantidad; j++) {
                    if (matriz[i][j] != matriz[j][i]) {
                        throw new IllegalArgumentException(
                            "La matriz debe ser simétrica."
                        );
                    }
                }
            }

            grafo = new Grafo();

            int centroX = panelDibujo.getWidth() / 2;
            int centroY = panelDibujo.getHeight() / 2;
            int radio = Math.max(0,
                Math.min(centroX, centroY) - 30
            );

            for (int i = 0; i < cantidad; i++) {

                double angulo = 2 * Math.PI * i / cantidad;

                int x = centroX + (int)(radio * Math.cos(angulo));
                int y = centroY + (int)(radio * Math.sin(angulo));

                Nodo nodo = new Nodo(
                    String.valueOf((char)('A' + i)), x, y
                );

                grafo.agregarNodo(nodo);
            }

            grafo.establecerMatriz(matriz);

            PanelGrafo dibujo = new PanelGrafo(grafo);

            panelDibujo.removeAll();
            panelDibujo.setLayout(new java.awt.BorderLayout());

            dibujo.setPreferredSize(new java.awt.Dimension(320, 200));
            panelDibujo.setPreferredSize(new java.awt.Dimension(320, 200));

            panelDibujo.add(dibujo, java.awt.BorderLayout.CENTER);

            panelDibujo.revalidate();
            panelDibujo.repaint();

            this.pack();
            this.setLocationRelativeTo(null);

            txtLista.setText(grafo.generarListaAdyacencia());

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Ingrese solamente números 0 y 1."
            );
        } catch (IllegalArgumentException e) {
            javax.swing.JOptionPane.showMessageDialog(
                this, e.getMessage()
            );
        }
    }//GEN-LAST:event_btnGenerarGrafoActionPerformed

