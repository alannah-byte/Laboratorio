    private void btnGenerarMatrizActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarMatrizActionPerformed
        // TODO add your handling code here:
            int cantidad = grafo.getNodos().size();

    if (cantidad == 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Primero debe agregar nodos."
        );
        return;
    }

    // Obtener la matriz del grafo
    int[][] matriz = grafo.getMatrizAdyacencia();

    // Crear nombres de las columnas
    String[] columnas = new String[cantidad];

    for (int i = 0; i < cantidad; i++) {
        columnas[i] = grafo.getNodos().get(i).getNombre();
    }

    // Crear los datos de la tabla
    Object[][] datos = new Object[cantidad][cantidad];

    for (int i = 0; i < cantidad; i++) {
        for (int j = 0; j < cantidad; j++) {
            datos[i][j] = matriz[i][j];
        }
    }

    // Mostrar la matriz
    DefaultTableModel modelo =
            new DefaultTableModel(datos, columnas) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
};

    tablaMatriz.setModel(modelo);

    // Mostrar la lista de adyacencia
    txtLista.setText(grafo.generarListaAdyacencia());
    }//GEN-LAST:event_btnGenerarMatrizActionPerformed

