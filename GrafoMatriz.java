    public GrafoMatriz() {
    initComponents();

    dibujo = new PanelGrafo(grafo);

    panelDibujo.setLayout(new java.awt.BorderLayout());
    panelDibujo.add(dibujo, java.awt.BorderLayout.CENTER);

    panelDibujo.revalidate();
    panelDibujo.repaint();

    dibujo.addMouseListener(new java.awt.event.MouseAdapter() {

        @Override
        public void mouseClicked(java.awt.event.MouseEvent evt) {

            if (modoAgregar) {

                int x = evt.getX();
                int y = evt.getY();

                int cantidad = grafo.getNodos().size();

                String nombre = String.valueOf(
                    (char) ('A' + cantidad)
                );

                Nodo nodo = new Nodo(nombre, x, y);
                grafo.agregarNodo(nodo);

                dibujo.repaint();
            }else if (modoConectar) {

    int x = evt.getX();
    int y = evt.getY();

    for (int i = 0; i < grafo.getNodos().size(); i++) {

        Nodo nodo = grafo.getNodos().get(i);

        double distancia = Math.sqrt(
            Math.pow(x - nodo.getX(), 2)
            + Math.pow(y - nodo.getY(), 2)
        );

        if (distancia <= 20) {

            if (nodoSeleccionado == -1) {

                nodoSeleccionado = i;

            } else {

                grafo.agregarArista(nodoSeleccionado, i);

                nodoSeleccionado = -1;

                dibujo.repaint();
            }

            break;
        }
    }
}
        }
    });
}
    

